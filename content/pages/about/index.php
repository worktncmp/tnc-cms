    <h1>What TNC-CMS is</h1>
    <p>TNC-CMS is a lightweight PHP website kit. It is not WordPress and not Laravel. You build sites by adding files in clear folders.</p>
    <ul>
        <li><code>content/pages</code> — normal website pages</li>
        <li><code>app/Views</code> — header, footer, layouts, components</li>
        <li><code>app/Controllers</code> — forms and database pages</li>
        <li><code>core</code> — the engine (leave this alone for a normal site)</li>
    </ul>
    <p>Full guides are in the <code>docs</code> folder.</p>
